#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(try_from = "String")]
pub struct Rgb(u8, u8, u8);

impl TryFrom<String> for Rgb {
    type Error = &'static str;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        let digits = value
            .strip_prefix('#')
            .filter(|digits| digits.len() == 6 && digits.bytes().all(|b| b.is_ascii_hexdigit()))
            .ok_or("expected a #RRGGBB color")?;
        let value = u32::from_str_radix(digits, 16).map_err(|_| "invalid RGB color")?;
        Ok(Self((value >> 16) as u8, (value >> 8) as u8, value as u8))
    }
}

#[derive(Deserialize)]
pub struct Theme {
    pub name: String,
    pub foreground: Rgb,
    pub background: Rgb,
    pub cursor: Option<Rgb>,
    pub selection: Option<Rgb>,
    pub meta: Metadata,
    #[serde(flatten)]
    pub palette: Palette,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Metadata {
    pub is_dark: bool,
    #[serde(default, deserialize_with = "deserialize_credits")]
    pub credits: Vec<Credit>,
}

#[derive(Debug, Deserialize, PartialEq, Eq)]
pub struct Credit {
    pub name: String,
    pub link: String,
}

fn deserialize_credits<'de, D: Deserializer<'de>>(
    deserializer: D,
) -> Result<Vec<Credit>, D::Error> {
    #[derive(Deserialize)]
    #[serde(untagged)]
    enum Credits {
        One(Credit),
        Many(Vec<Credit>),
    }

    Ok(match Option::<Credits>::deserialize(deserializer)? {
        Some(Credits::One(credit)) => vec![credit],
        Some(Credits::Many(credits)) => credits,
        None => Vec::new(),
    })
}

pub struct Palette {
    pub normal: [Rgb; 8],
    pub bright: [Rgb; 8],
}

impl<'de> Deserialize<'de> for Palette {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        #[derive(Deserialize)]
        #[serde(rename_all = "camelCase")]
        struct Colors {
            black: Rgb,
            red: Rgb,
            green: Rgb,
            yellow: Rgb,
            blue: Rgb,
            magenta: Rgb,
            cyan: Rgb,
            white: Rgb,
            bright_black: Rgb,
            bright_red: Rgb,
            bright_green: Rgb,
            bright_yellow: Rgb,
            bright_blue: Rgb,
            bright_magenta: Rgb,
            bright_cyan: Rgb,
            bright_white: Rgb,
        }

        let colors = Colors::deserialize(deserializer)?;
        Ok(Self {
            normal: [
                colors.black,
                colors.red,
                colors.green,
                colors.yellow,
                colors.blue,
                colors.magenta,
                colors.cyan,
                colors.white,
            ],
            bright: [
                colors.bright_black,
                colors.bright_red,
                colors.bright_green,
                colors.bright_yellow,
                colors.bright_blue,
                colors.bright_magenta,
                colors.bright_cyan,
                colors.bright_white,
            ],
        })
    }
}

fn generate(themes: &[Theme]) -> io::Result<String> {
    let mut output = String::from(
        "// Generated by tools/theme-generator. Do not edit.\n\
         // Data: assets/vhs/themes.json (see assets/vhs/LICENSE).\n\n\
         use crate::{filter_criteria::ThemeMetrics, theme::{Credit, Metadata, Palette, Rgb, Theme}};\n\n\
         pub static THEMES: &[Theme] = &[\n",
    );
    for theme in themes {
        let metrics =
            ThemeMetrics::calculate(theme.foreground, theme.background).map_err(|error| {
                io::Error::new(
                    io::ErrorKind::InvalidData,
                    format!("{}: {error}", theme.name),
                )
            })?;
        writeln!(output, "Theme {{").unwrap();
        writeln!(output, "name: {:?},", theme.name).unwrap();
        writeln!(output, "foreground: {:?},", theme.foreground).unwrap();
        writeln!(output, "background: {:?},", theme.background).unwrap();
        writeln!(output, "cursor: {:?},", theme.cursor).unwrap();
        writeln!(output, "selection: {:?},", theme.selection).unwrap();
        writeln!(
            output,
            "meta: Metadata {{ is_dark: {}, credits: &[",
            theme.meta.is_dark,
        )
        .unwrap();
        for credit in &theme.meta.credits {
            writeln!(
                output,
                "Credit {{ name: {:?}, link: {:?} }},",
                credit.name, credit.link,
            )
            .unwrap();
        }
        output.push_str("] },\n");
        writeln!(
            output,
            "palette: Palette {{ normal: {:?}, bright: {:?} }},",
            theme.palette.normal, theme.palette.bright,
        )
        .unwrap();
        writeln!(output, "metrics: {metrics:?},").unwrap();
        output.push_str("},\n");
    }
    output.push_str("];\n");
    Ok(output)
}

fn write_catalog(path: &Path, catalog: &str) -> io::Result<()> {
    let parent = path.parent().expect("catalog path has a parent directory");
    fs::create_dir_all(parent)?;
    let mut file = tempfile::Builder::new().suffix(".rs").tempfile_in(parent)?;
    file.write_all(catalog.as_bytes())?;
    let status = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(file.path())
        .status()?;
    if !status.success() {
        return Err(io::Error::other("rustfmt failed to format the catalog"));
    }
    file.persist(path).map_err(|error| error.error)?;
    Ok(())
}

fn main() -> io::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("generator is under tools/theme-generator");
    let themes = parse(&fs::read_to_string(root.join("assets/vhs/themes.json"))?)?;
    write_catalog(&root.join("src/theme/catalog.rs"), &generate(&themes)?)?;
    println!("Generated {} themes in src/theme/catalog.rs", themes.len());
    Ok(())
}

fn parse(data: &str) -> io::Result<Vec<Theme>> {
    let mut themes: Vec<Theme> = serde_json::from_str(data)
        .map_err(|error| io::Error::new(io::ErrorKind::InvalidData, error))?;
    if themes.is_empty() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "the bundled theme catalog is empty",
        ));
    }
    themes.sort_by(|left, right| left.name.cmp(&right.name));
    for theme in &themes {
        if theme.name.is_empty() || theme.name.trim() != theme.name {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "theme names must be non-empty and have no surrounding whitespace",
            ));
        }
    }
    for pair in themes.windows(2) {
        if pair[0].name == pair[1].name {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                format!("duplicate theme name: {}", pair[0].name),
            ));
        }
    }
    Ok(themes)
}

#[cfg(test)]
mod tests {
    use rstest::rstest;
    use serde_json::{Value, json};

    use super::*;

    #[rstest]
    #[case(None, &[])]
    #[case(Some(json!(null)), &[])]
    #[case(Some(json!([])), &[])]
    #[case(Some(json!({"name": "Source", "link": "https://example.com/source"})), &[("Source", "https://example.com/source")])]
    #[case(Some(json!([{"name": "Source", "link": "https://example.com/source"}])), &[("Source", "https://example.com/source")])]
    #[case(Some(json!([
        {"name": "Original", "link": "https://example.com/original"},
        {"name": "Port", "link": "https://example.com/port"}
    ])), &[("Original", "https://example.com/original"), ("Port", "https://example.com/port")])]
    fn credits_accept_upstream_shapes_and_preserve_order(
        #[case] credits: Option<Value>,
        #[case] expected: &[(&str, &str)],
    ) {
        let mut metadata = json!({"isDark": true});
        if let Some(credits) = credits {
            metadata["credits"] = credits;
        }
        let metadata: Metadata = serde_json::from_value(metadata).unwrap();
        let actual: Vec<_> = metadata
            .credits
            .iter()
            .map(|credit| (credit.name.as_str(), credit.link.as_str()))
            .collect();
        assert_eq!(actual, expected);
    }

    #[rstest]
    #[case("empty")]
    #[case("duplicate")]
    #[case("empty name")]
    #[case("padded name")]
    #[case("missing foreground")]
    #[case("invalid ANSI color")]
    #[case("invalid cursor")]
    #[case("invalid selection")]
    #[case("missing isDark")]
    #[case("invalid isDark")]
    fn rejects_invalid_catalogs(#[case] fault: &str) {
        let mut entries: Vec<Value> =
            serde_json::from_str(include_str!("../../../assets/vhs/themes.json")).unwrap();
        entries.truncate(1);
        match fault {
            "empty" => entries.clear(),
            "duplicate" => entries.push(entries[0].clone()),
            "empty name" => entries[0]["name"] = json!(""),
            "padded name" => entries[0]["name"] = json!(" padded "),
            "missing foreground" => {
                entries[0].as_object_mut().unwrap().remove("foreground");
            }
            "invalid ANSI color" => entries[0]["brightRed"] = json!("#12345g"),
            "invalid cursor" => entries[0]["cursor"] = json!("#12345g"),
            "invalid selection" => entries[0]["selection"] = json!("red"),
            "missing isDark" => {
                entries[0]["meta"].as_object_mut().unwrap().remove("isDark");
            }
            "invalid isDark" => entries[0]["meta"]["isDark"] = json!("dark"),
            _ => unreachable!(),
        }
        let error = parse(&serde_json::to_string(&entries).unwrap())
            .err()
            .unwrap();
        assert_eq!(error.kind(), io::ErrorKind::InvalidData);
    }
}
